#Grocery List: Manages a list of items to buy at the store.
grocery_list = ["milk", "eggs", "bread", "butter", "cheese"]
#append adds an item to the end of the list
grocery_list.append("fruits")
print(grocery_list)
#len returns the number of items in the list
print("Total items in the grocery list:", len(grocery_list))
print("The first item in the grocery list is:", grocery_list[0])